const { chromium } = require('playwright');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true, ...(process.env.SDE_BROWSER_PATH?{executablePath:process.env.SDE_BROWSER_PATH}:{})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto((process.env.SDE_BASE_URL||'http://127.0.0.1:8000')+'/#token='+encodeURIComponent(process.env.SDE_API_TOKEN||''));
 await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
 await page.screenshot({path:'evidence/overview.png',fullPage:true});
 await page.getByRole('button',{name:'Try the included demo'}).click();
 await page.getByRole('button',{name:'Build a plan'}).click();
 await page.getByRole('button',{name:'Approve action',exact:true}).waitFor({timeout:15000});
 await page.screenshot({path:'evidence/approval.png',fullPage:true});
 await page.getByRole('button',{name:'Approve action',exact:true}).click();
 await page.getByText('Tests passed; inspect the diff and acceptance criteria.',{exact:true}).first().waitFor({timeout:20000});
 await page.getByRole('heading',{name:'After the change',exact:true}).waitFor();
 await page.locator('#notice').waitFor({state:'hidden'});
 await page.screenshot({path:'evidence/verification.png',fullPage:true});
 await page.getByRole('button',{name:'Connections',exact:true}).click();
 await page.getByRole('heading',{name:'Connections',exact:true}).waitFor();
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.getByRole('button',{name:'Verify audit chain'}).click();
 await page.getByRole('status').filter({hasText:'Audit chain verified.'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
 await page.locator('#notice').waitFor({state:'hidden'});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Mobile horizontal overflow');
 await page.screenshot({path:'evidence/mobile.png',fullPage:true});
 fs.writeFileSync('evidence/browser-check.json',JSON.stringify({status:errors.length?'failed':'passed',errors,mobile_horizontal_overflow:overflow,viewport_desktop:'1440x1000',viewport_mobile:'390x844',flow:'intake, approval, actual tests, evidence, connections, audit integrity, mobile overview'},null,2));
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
